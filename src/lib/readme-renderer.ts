/**
 * Pure function that renders a structured analysis into a full Markdown README.
 *
 * `renderReadme(analysis, sections, meta?)` walks the user-edited section
 * order, emitting only enabled sections. Each section's content is taken
 * verbatim from the Section.content string (so the LLM and the user both edit
 * the same string), and prefixed with a `## Label` heading.
 *
 * Badges are derived from analysis + meta and rendered as shields.io static
 * badge URLs — they're placeholders that always render even when the actual
 * build status is unknown.
 *
 * The ASCII project structure tree is computed from the GitHub tree (only
 * top-level entries by default, plus the first level under each top-level
 * directory).
 */

import type { CommitEntry, RepoAnalysis, RepoMeta, Section, TreeEntry } from '@/lib/types'

export interface RenderOptions {
  /** Number of commits to render in the "Recent commits" table. Default 10. */
  recentCommitsCount?: number
}

export function renderReadme(
  analysis: RepoAnalysis,
  sections: Section[],
  meta?: RepoMeta,
  opts: RenderOptions = {},
): string {
  const recentCommitsCount = opts.recentCommitsCount ?? 10
  const parts: string[] = []

  // Title + tagline (always emitted — it's the README header, not a section).
  const title = meta?.name || analysis.tagline || 'Untitled'
  parts.push(`# ${title}`)
  if (analysis.tagline) parts.push('')
  if (analysis.tagline) parts.push(`> ${analysis.tagline}`)
  parts.push('')

  // Badges (always emitted).
  parts.push(renderBadges(analysis, meta))
  parts.push('')

  // Walk the user's section list in order.
  for (const section of sections) {
    if (!section.enabled) continue
    parts.push(`## ${section.label}`)
    parts.push('')
    parts.push(section.content.trim())
    parts.push('')
  }

  return parts.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n'
}

export function renderBadges(analysis: RepoAnalysis, meta?: RepoMeta): string {
  const badges: string[] = []
  const license = analysis.license || (meta?.license ?? 'MIT')
  badges.push(shield('license', license, 'blue'))
  if (meta?.language) badges.push(shield('language', meta.language, 'orange'))
  if (meta?.stars !== undefined) badges.push(shield('stars', String(meta.stars), 'yellow'))
  badges.push(shield('build', 'unknown', 'lightgrey'))
  // A static "made with" badge so the README always shows a non-empty block.
  badges.push(shield('made%20with', 'Coffee', 'ff69b4'))
  return badges.join(' ')
}

function shield(label: string, value: string, color: string): string {
  return `![${label}](https://img.shields.io/badge/${encodeURIComponent(label)}-${encodeURIComponent(value)}-${color})`
}

/** Default section template generated by the analyzer. */
export function defaultSections(analysis: RepoAnalysis, meta?: RepoMeta): Section[] {
  const sections: Section[] = [
    {
      id: 'description',
      label: 'Description',
      enabled: true,
      content: analysis.description,
    },
    {
      id: 'features',
      label: 'Features',
      enabled: true,
      content: renderFeatures(analysis),
    },
    {
      id: 'tech-stack',
      label: 'Tech Stack',
      enabled: true,
      content: renderTechStack(analysis),
    },
    {
      id: 'getting-started',
      label: 'Getting Started',
      enabled: true,
      content: renderGettingStarted(analysis, meta),
    },
    {
      id: 'structure',
      label: 'Project Structure',
      enabled: true,
      content: renderStructure(meta),
    },
    {
      id: 'recent-commits',
      label: 'Recent Commits',
      enabled: true,
      content: renderRecentCommits(meta),
    },
    {
      id: 'contributing',
      label: 'Contributing',
      enabled: true,
      content: [
        'Contributions are welcome!',
        '',
        '1. Fork the repository',
        '2. Create a feature branch (`git checkout -b feature/amazing`)',
        '3. Commit your changes (`git commit -m "Add amazing"`)',
        '4. Push to the branch (`git push origin feature/amazing`)',
        '5. Open a Pull Request',
        '',
        'Please make sure your code passes the existing tests before submitting.',
      ].join('\n'),
    },
    {
      id: 'license',
      label: 'License',
      enabled: true,
      content: renderLicense(analysis),
    },
  ]
  return sections
}

function renderFeatures(analysis: RepoAnalysis): string {
  if (!analysis.features || analysis.features.length === 0) return '_(No features listed.)_'
  return analysis.features.map((f) => `- ${f}`).join('\n')
}

function renderTechStack(analysis: RepoAnalysis): string {
  if (!analysis.techStack || analysis.techStack.length === 0) {
    return '_(Tech stack not detected — add your own entries.)_'
  }
  const rows = analysis.techStack.map((r) => `| ${r.name} | ${r.role} |`).join('\n')
  return `| Tool / Library | Role |\n| --- | --- |\n${rows}`
}

function renderGettingStarted(analysis: RepoAnalysis, meta?: RepoMeta): string {
  const lines: string[] = []
  const ecosystem = meta?.manifest?.ecosystem
  const installCmds = analysis.gettingStarted.install.length
    ? analysis.gettingStarted.install
    : defaultInstall(ecosystem)
  const runCmds = analysis.gettingStarted.run.length
    ? analysis.gettingStarted.run
    : defaultRun(ecosystem, meta?.manifest?.scripts)

  lines.push('### Prerequisites', '')
  lines.push('- [Git](https://git-scm.com/)')
  if (ecosystem === 'npm') lines.push('- [Node.js](https://nodejs.org/) (LTS recommended)')
  if (ecosystem === 'poetry' || ecosystem === 'pep621') lines.push('- [Python](https://www.python.org/) 3.10+')
  if (ecosystem === 'cargo') lines.push('- [Rust](https://www.rust-lang.org/tools/install)')
  if (ecosystem === 'go') lines.push('- [Go](https://go.dev/dl/)')
  lines.push('')

  lines.push('### Install', '')
  lines.push('```bash')
  for (const cmd of installCmds) lines.push(cmd)
  lines.push('```', '')

  lines.push('### Run', '')
  lines.push('```bash')
  for (const cmd of runCmds) lines.push(cmd)
  lines.push('```')

  if (analysis.gettingStarted.notes) {
    lines.push('', '### Notes', '', analysis.gettingStarted.notes)
  }

  return lines.join('\n')
}

function defaultInstall(ecosystem?: string): string[] {
  switch (ecosystem) {
    case 'npm':
      return ['git clone <repo-url>', 'cd <repo-name>', 'npm install']
    case 'poetry':
      return ['git clone <repo-url>', 'cd <repo-name>', 'poetry install']
    case 'pep621':
      return ['git clone <repo-url>', 'cd <repo-name>', 'pip install -e .']
    case 'cargo':
      return ['git clone <repo-url>', 'cd <repo-name', 'cargo build --release']
    case 'go':
      return ['git clone <repo-url>', 'cd <repo-name', 'go mod download']
    default:
      return ['git clone <repo-url>', 'cd <repo-name>']
  }
}

function defaultRun(ecosystem?: string, scripts?: Record<string, string>): string[] {
  if (scripts && Object.keys(scripts).length > 0) {
    if (ecosystem === 'npm') {
      // Prefer dev, then start, then first script.
      const preferred = ['dev', 'start', 'serve']
      for (const p of preferred) {
        if (scripts[p]) return [`npm run ${p}`]
      }
      const first = Object.keys(scripts)[0]
      return [`npm run ${first}`]
    }
    if (ecosystem === 'poetry' || ecosystem === 'pep621') {
      const first = Object.keys(scripts)[0]
      return [`poetry run ${first}`]
    }
  }
  switch (ecosystem) {
    case 'npm':
      return ['npm run dev']
    case 'cargo':
      return ['cargo run']
    case 'go':
      return ['go run .']
    default:
      return ['# Add your run command here']
  }
}

function renderStructure(meta?: RepoMeta): string {
  if (!meta || !meta.tree || meta.tree.length === 0) {
    return '_(Repository tree not available — clone the repo and run `tree -L 2` to populate this section.)_'
  }
  const tree = renderAsciiTree(meta.tree)
  return '```text\n' + tree + '\n```'
}

function renderAsciiTree(entries: TreeEntry[]): string {
  // Reduce to top-level + one level under each top-level directory.
  const top = entries.filter((e) => !e.path.includes('/'))
  const byDir = new Map<string, TreeEntry[]>()
  for (const e of entries) {
    if (e.path.includes('/')) {
      const dir = e.path.split('/')[0]
      if (!byDir.has(dir)) byDir.set(dir, [])
      byDir.get(dir)!.push(e)
    }
  }

  const lines: string[] = [`${shortenName(entries.length ? guessRoot(entries) : '.')}/`]
  const sortedTop = [...top].sort((a, b) => {
    if (a.type !== b.type) return a.type === 'tree' ? -1 : 1
    return a.path.localeCompare(b.path)
  })
  for (let i = 0; i < sortedTop.length; i++) {
    const e = sortedTop[i]
    const isLast = i === sortedTop.length - 1
    const prefix = isLast ? '└── ' : '├── '
    const suffix = e.type === 'tree' ? '/' : ''
    lines.push(`${prefix}${e.path}${suffix}`)
    if (e.type === 'tree' && byDir.has(e.path)) {
      const children = byDir.get(e.path)!
        .filter((c) => c.path.split('/').length === 2)
        .sort((a, b) => {
          if (a.type !== b.type) return a.type === 'tree' ? -1 : 1
          return a.path.localeCompare(b.path)
        })
        .slice(0, 5)
      const childPrefix = isLast ? '    ' : '│   '
      for (let j = 0; j < children.length; j++) {
        const c = children[j]
        const cLast = j === children.length - 1
        const cPrefix = cLast ? '└── ' : '├── '
        const cSuffix = c.type === 'tree' ? '/' : ''
        lines.push(`${childPrefix}${cPrefix}${c.path.split('/').slice(1).join('/')}${cSuffix}`)
      }
    }
  }
  return lines.join('\n')
}

function guessRoot(entries: TreeEntry[]): string {
  // Best-effort: if every path starts with the same segment, that's the root.
  if (entries.length === 0) return '.'
  return '.'
}

function shortenName(_: number): string {
  return '.'
}

function renderRecentCommits(meta?: RepoMeta, count = 10): string {
  if (!meta || !meta.commits || meta.commits.length === 0) {
    return '_(Recent commits not available.)_'
  }
  const rows: string[] = ['| SHA | Message | Author | Date |', '| --- | --- | --- | --- |']
  for (const c of meta.commits.slice(0, count) as CommitEntry[]) {
    const sha = c.sha.slice(0, 7)
    const msg = (c.message || '').split('\n')[0].slice(0, 80).replace(/\|/g, '\\|')
    const author = (c.author || 'unknown').replace(/\|/g, '\\|')
    const date = (c.date || '').slice(0, 10)
    rows.push(`| \`${sha}\` | ${msg} | ${author} | ${date} |`)
  }
  return rows.join('\n')
}

function renderLicense(analysis: RepoAnalysis): string {
  const lic = analysis.license || 'MIT'
  return [
    `This project is licensed under the ${lic} License — see the [LICENSE](LICENSE) file for details.`,
  ].join('\n')
}
